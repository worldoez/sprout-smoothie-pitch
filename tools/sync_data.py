#!/usr/bin/env python3
"""Rebuild PRESENTATION/content/data.js from the R outputs and copy figures.

Run after re-running the R pipeline:  python3 PRESENTATION/tools/sync_data.py
"""
import csv, json, shutil, datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
PRES = HERE.parent
OUT = PRES.parent / "output"
TABLES = [
    "01_funnel", "02_sample_profile", "02_shops_used", "02_importance", "02_likert_summary",
    "02_drinks_per_week", "03_price_summary", "03_demand_curve", "03_candidate_prices",
    "04_fruit", "04_base", "04_addons", "04_where", "04_occasion", "05_segments",
    "05_intent_distribution", "06_theme_counts", "08_tier_stability", "09_sample_size_targets",
    "10_question_coverage",
]


def num(v):
    if v is None or v == "" or v == "NA":
        return None
    try:
        return int(v)
    except ValueError:
        try:
            return float(v)
        except ValueError:
            return v


def main():
    data = {}
    for name in TABLES:
        p = OUT / "tables" / f"{name}.csv"
        if not p.exists():
            print("warning: missing", p)
            continue
        with p.open(encoding="utf-8-sig", newline="") as f:
            data[name] = [{k: num(v) for k, v in row.items()} for row in csv.DictReader(f)]
    res = OUT / "results.json"
    if res.exists():
        data["results"] = json.loads(res.read_text(encoding="utf-8"))
    data["generated"] = datetime.datetime.now().isoformat(timespec="seconds")

    js = ("// AUTO-GENERATED by tools/sync_data.py from output/tables — do not edit by hand.\n"
          "window.CONTENT = window.CONTENT || {};\n"
          "window.CONTENT.data = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    (PRES / "content" / "data.js").write_text(js, encoding="utf-8")

    figs = PRES / "assets" / "figures"
    figs.mkdir(parents=True, exist_ok=True)
    n = 0
    for png in (OUT / "figures").glob("*.png"):
        shutil.copy2(png, figs / png.name)
        n += 1
    print(f"wrote content/data.js ({len(data) - 1} tables) and copied {n} figures")


if __name__ == "__main__":
    main()
